# Task 1 Solution

def greet(name):
    """
    Simple function that greets a person.
    
    Args:
        name (str): The person's name
    
    Returns:
        str: Greeting message
    """
    return f"Hello, {name}! Welcome to the Official Project."

# Example usage
if __name__ == "__main__":
    print(greet("Njihia27"))
    print(greet("Developer"))
